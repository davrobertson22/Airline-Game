// @not-a-test — fits per-airport road factors from data/osrm-drive.json and
// WRITES src/data/demandV2Roads.js. Re-run after fetch-osrm.mjs.
//
//   node tools/demand-audit/fit-roads.mjs [--dry]
//
// The v2 drive ramp is a function of how long the DRIVE takes, not of the
// great-circle distance: Seattle–Spokane is 360 km but a mountain pass, Miami–
// Orlando 310 km of flat interstate. Storing every pair's driving time would be
// tens of thousands of entries, so instead:
//
//   log(drive minutes) = ALPHA + BETA·log(great-circle km) + u_i + u_j
//
// fitted by alternating least squares, one road factor exp(u) per airport
// (> 1 = slow roads out of here: mountains, water, a long way round).
// Airports with no road to any neighbour are listed so the isolated sets can
// be checked against them.

import { readFileSync, writeFileSync } from 'fs';
import { getAirport } from '../../src/data/airports.js';
import { distanceKm } from '../../src/utils/market.js';

const DRY = process.argv.includes('--dry');
const RIDGE = 2;   // pseudo-pairs pulling each u toward 0
const cache = JSON.parse(readFileSync(new URL('./data/osrm-drive.json', import.meta.url), 'utf8'));
const obs = [], noRoad = new Map(), seen = new Map();
for (const [key, v] of Object.entries(cache.pairs)) {
  const [a, b] = key.split('|');
  const A = getAirport(a), B = getAirport(b);
  if (!A || !B) continue;
  for (const c of [a, b]) seen.set(c, (seen.get(c) ?? 0) + 1);
  if (v == null || !(v[0] > 0)) { for (const c of [a, b]) noRoad.set(c, (noRoad.get(c) ?? 0) + 1); continue; }
  const km = distanceKm(A, B);
  if (km < 5) continue;
  obs.push({ a, b, lk: Math.log(km), lm: Math.log(v[0]) });
}
const u = new Map();
let alpha = 0, beta = 1;
for (let it = 0; it < 50; it++) {
  // global terms given u
  let sx = 0, sy = 0, sxx = 0, sxy = 0;
  for (const o of obs) { const y = o.lm - (u.get(o.a) ?? 0) - (u.get(o.b) ?? 0); sx += o.lk; sy += y; sxx += o.lk * o.lk; sxy += o.lk * y; }
  const n = obs.length; beta = (n * sxy - sx * sy) / (n * sxx - sx * sx); alpha = (sy - beta * sx) / n;
  // u given globals
  const s = new Map(), c = new Map();
  for (const o of obs) {
    const r = o.lm - alpha - beta * o.lk;
    s.set(o.a, (s.get(o.a) ?? 0) + r - (u.get(o.b) ?? 0)); c.set(o.a, (c.get(o.a) ?? 0) + 1);
    s.set(o.b, (s.get(o.b) ?? 0) + r - (u.get(o.a) ?? 0)); c.set(o.b, (c.get(o.b) ?? 0) + 1);
  }
  for (const [k, v] of s) u.set(k, v / (c.get(k) + RIDGE));
}
const res = obs.map((o) => o.lm - alpha - beta * o.lk - (u.get(o.a) ?? 0) - (u.get(o.b) ?? 0));
const res0 = obs.map((o) => o.lm - alpha - beta * o.lk);
const sd = (x) => { const m = x.reduce((p, q) => p + q, 0) / x.length; return Math.sqrt(x.reduce((p, q) => p + (q - m) ** 2, 0) / x.length); };
console.log(`${obs.length} road pairs. drive min = ${Math.exp(alpha).toFixed(3)} x km^${beta.toFixed(3)}`);
console.log(`log error: distance only ${sd(res0).toFixed(3)} (~${Math.round(100 * (Math.exp(sd(res0)) - 1))}%), with road factors ${sd(res).toFixed(3)} (~${Math.round(100 * (Math.exp(sd(res)) - 1))}%)`);
const fac = Object.fromEntries([...u].map(([k, v]) => [k, +Math.exp(v).toFixed(3)]).filter(([, f]) => Math.abs(f - 1) >= 0.005).sort(([x], [y]) => (x < y ? -1 : 1)));
const srt = Object.entries(fac).sort((x, y) => x[1] - y[1]);
const lab = ([c, f]) => `${c} ${getAirport(c)?.city} ${f}`;
console.log('fastest roads:', srt.slice(0, 6).map(lab).join(', '));
console.log('slowest roads:', srt.slice(-10).reverse().map(lab).join(', '));
const allNo = [...noRoad].filter(([c, n]) => n === seen.get(c)).map(([c]) => c);
console.log('no road to ANY neighbour:', allNo.join(' ') || 'none');
console.log('some neighbours unreachable:', [...noRoad].filter(([c, n]) => n < seen.get(c)).map(([c, n]) => `${c}(${n}/${seen.get(c)})`).join(' '));
for (const [a, b] of [['SEA', 'GEG'], ['MIA', 'MCO'], ['LAS', 'RNO'], ['JFK', 'BUF'], ['LAX', 'SFO'], ['DEN', 'ASE'], ['SYD', 'CBR']]) {
  const k = a < b ? `${a}|${b}` : `${b}|${a}`; const v = cache.pairs[k];
  const est = Math.exp(alpha) * Math.pow(distanceKm(getAirport(a), getAirport(b)), beta) * (fac[a] ?? 1) * (fac[b] ?? 1);
  console.log(`  ${a}-${b}: OSRM ${v ? (v[0] / 60).toFixed(1) + 'h' : 'n/a'}, estimate ${(est / 60).toFixed(1)}h`);
}
if (!DRY) {
  writeFileSync(new URL('../../src/data/demandV2Roads.js', import.meta.url), `// GENERATED by tools/demand-audit/fit-roads.mjs — do not hand-edit.
// Driving-time model for demand model v2 (utils/market.js), fitted to
// ${obs.length} OSRM car-profile drive times between US and Australian airports:
//   drive minutes ≈ ROAD_ALPHA × greatCircleKm^ROAD_BETA × ROAD_FACTORS[a] × ROAD_FACTORS[b]
// (log error ${sd(res).toFixed(3)}). Factor > 1 = slow roads out of that airport.
export const ROAD_ALPHA = ${+Math.exp(alpha).toFixed(4)};
export const ROAD_BETA = ${+beta.toFixed(4)};
export const ROAD_FACTORS = {
${Object.entries(fac).map(([c, f]) => `  ${c}: ${f},`).join('\n')}
};
`);
  console.log(`wrote src/data/demandV2Roads.js (${Object.keys(fac).length} factors)`);
}
